import path from "node:path";

import { exists, importModule } from "./fs-utils";
import { type GeneratedMenu, type GeneratedRoute, type MenuGroup, type Section, SECTIONS } from "./types";

function isKnownRoute(name: string | undefined, known: Set<string>): boolean {
  return name === undefined || known.has(name);
}

function filterMenu(menu: MenuGroup, known: Set<string>, addon: string): { menu: MenuGroup; count: number } {
  const filtered: MenuGroup = {};
  let count = 0;

  for (const [group, items] of Object.entries(menu)) {
    const kept = items.filter((item) => {
      if (isKnownRoute(item.link?.name, known)) {
        return true;
      }

      console.warn(
        `[addons] Skipping add-on menu item "${item.name}": unknown route "${item.link?.name}" from ${addon}`
      );

      return false;
    });

    if (kept.length > 0) {
      filtered[group] = kept;
      count += kept.length;
    }
  }

  return { menu: filtered, count };
}

export async function collectMenus(
  root: string,
  addon: string,
  known: Set<string>
): Promise<{ menus: GeneratedMenu[]; count: number }> {
  const menus: GeneratedMenu[] = [];
  let count = 0;

  for (const section of SECTIONS) {
    const file = path.join(root, addon, "web", "pages", section, "menu.ts");

    if (!(await exists(file))) {
      continue;
    }

    try {
      const module = await importModule(file);
      const menu = (module.menu ?? module.default) as MenuGroup | undefined;

      if (!menu || typeof menu !== "object") {
        continue;
      }

      const filtered = filterMenu(menu, known, addon);

      if (filtered.count > 0) {
        menus.push({ section, menu: filtered.menu });
        count += filtered.count;
      }
    } catch (error) {
      console.warn(`[addons] Skipping add-on menu ${file}: ${(error as Error).message}`);
    }
  }

  return { menus, count };
}

export function registrySource(routes: GeneratedRoute[], menus: GeneratedMenu[]): string {
  const routeDefs = routes.map((route) => ({ name: route.name, pattern: route.pattern }));
  const groups: Record<Section, MenuGroup[]> = { admin: [], profile: [], project: [] };

  for (const entry of menus) {
    groups[entry.section].push(entry.menu);
  }

  return `// Generated by scripts/addons/generate.ts. Do not edit.
import type { MenuSection } from "$lib/addons/register";
import type { RouteDef } from "$lib/navigation/registry";
import type { MenuGroup } from "$lib/utils";

export const routes: RouteDef[] = ${JSON.stringify(routeDefs, null, 2)};

export const menus: Record<MenuSection, MenuGroup[]> = ${JSON.stringify(groups, null, 2)};
`;
}
